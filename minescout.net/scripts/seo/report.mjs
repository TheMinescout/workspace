// Human-readable inventory of every page the site serves, plus the validation
// findings for it. Committed at seo/INVENTORY.md so a review can see the whole
// picture without running anything.
export function renderReport({ manifest, pages, issues, sitemap }) {
  const byPath = new Map(pages.map((page) => [page.path, page]));
  const errors = issues.filter((entry) => entry.level === "error");
  const warnings = issues.filter((entry) => entry.level === "warn");
  const kinds = {};
  for (const page of manifest.pages) kinds[page.kind] = (kinds[page.kind] ?? 0) + 1;

  const lines = [];
  lines.push("# Page inventory and metadata report");
  lines.push("");
  lines.push("Generated by `npm run seo:report` from `public/views.js`, `public/**/*.html` and");
  lines.push("`seo/overrides.json`. Do not edit by hand: regenerate after changing a page.");
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push(`- Pages discovered: **${manifest.pages.length}**`);
  lines.push(`- Indexable and released: **${manifest.pages.filter((page) => page.indexable && page.released).length}**`);
  lines.push(`- Listed in sitemap.xml: **${sitemap.length}**`);
  lines.push(`- Metadata errors: **${errors.length}**, warnings: **${warnings.length}**`);
  lines.push("");
  lines.push("| Kind | Pages |");
  lines.push("| --- | --- |");
  for (const kind of Object.keys(kinds).sort()) lines.push(`| ${kind} | ${kinds[kind]} |`);
  lines.push("");
  lines.push("## Pages");
  lines.push("");
  lines.push("| Path | Kind | Index | Source | Title (chars) | Description (chars) | H1 | Words |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const page of manifest.pages) {
    const source = byPath.get(page.path);
    const title = page.title.replace(/\|/g, "\\|");
    lines.push(
      `| \`${page.path}\` | ${page.kind} | ${page.indexable ? (page.released ? "yes" : "scheduled") : "no"} | ${page.source} | ${title} (${page.title.length}) | ${page.description.length} | ${source?.h1s.length ?? 0} | ${page.words ?? "—"} |`,
    );
  }
  lines.push("");

  const sitemapSet = new Set(sitemap);
  const shouldBeListed = manifest.pages.filter((page) => page.indexable && page.released);
  const missingFromSitemap = shouldBeListed.filter((page) => !sitemapSet.has(page.url));
  const listedButNotIndexable = manifest.pages.filter((page) => sitemapSet.has(page.url) && !(page.indexable && page.released));

  lines.push("## Sitemap");
  lines.push("");
  lines.push(`- URLs listed: **${sitemap.length}**`);
  lines.push(`- Indexable pages missing from sitemap.xml: **${missingFromSitemap.length}**`);
  lines.push(`- Listed but not currently indexable: **${listedButNotIndexable.length}**`);
  lines.push("");
  if (missingFromSitemap.length) {
    lines.push("Missing:");
    for (const page of missingFromSitemap) lines.push(`- \`${page.path}\` — add a \`<url>\` to public/sitemap.xml`);
    lines.push("");
  }
  if (listedButNotIndexable.length) {
    lines.push("Listed early:");
    for (const page of listedButNotIndexable) {
      lines.push(`- \`${page.path}\` — ${page.released ? "noindex" : "scheduled; the URL 404s until it releases"}`);
    }
    lines.push("");
  }

  const section = (title, entries) => {
    lines.push(`## ${title}`);
    lines.push("");
    if (!entries.length) {
      lines.push("None.");
    } else {
      for (const entry of entries) {
        const where = entry.sourceFile ? ` (\`${entry.sourceFile}\`)` : "";
        lines.push(`- **${entry.path ?? "site"}** — ${entry.message}${where}`);
      }
    }
    lines.push("");
  };

  section(`Errors (${errors.length})`, errors);
  section(`Warnings (${warnings.length})`, warnings);

  return `${lines.join("\n")}\n`;
}
